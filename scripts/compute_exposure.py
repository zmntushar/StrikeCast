"""Pre-compute wave exposure geometry for every configured spot.

For each spot, 36 rays (every 10°) are cast over the NOAA NCEI DEM mosaic out to
100 km. Each ray records the over-water fetch to the first land, the mean depth
along it, and whether it reaches open ocean. The DEM depth at the spot's
offshore wave-model point is stored too.

Run after adding or moving a spot:

    python scripts/compute_exposure.py            # all spots
    python scripts/compute_exposure.py captree    # one spot

Results go to configs/exposure.yaml (reviewable, versioned). Spots missing from
that file (custom locations) are ray-cast at run time instead.
"""
from __future__ import annotations

import asyncio
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.core.geo import compass  # noqa: E402
from app.core.http import HttpClient  # noqa: E402
from app.providers.geography import exposure_rays  # noqa: E402
from app.services.forecast import load_spots  # noqa: E402

OUT = ROOT / "configs" / "exposure.yaml"


async def main(only: list[str]) -> None:
    spots = [s for s in load_spots() if not only or s.id in only]
    existing = yaml.safe_load(OUT.read_text(encoding="utf-8")) if OUT.exists() else {}
    data = existing.get("spots", {}) if existing else {}
    async with HttpClient() as http:
        for sp in spots:
            ex = await exposure_rays(http, sp.lat, sp.lon, sp.boundary_point() if sp.is_open_ocean else None)
            data[sp.id] = ex.to_dict()
            open_dirs = [compass(d) for d, o in zip(ex.dirs_deg, ex.open_ocean) if o]
            print(f"{sp.id:30s} open-ocean rays: {len(open_dirs):2d} {' '.join(open_dirs[:12])}"
                  f"  boundary depth: {ex.boundary_depth_m} m")
    header = ("# GENERATED by scripts/compute_exposure.py from the NOAA NCEI DEM mosaic — do not hand-edit.\n"
              "# dirs_deg = direction each ray points (= direction wind/waves come FROM);\n"
              "# fetch_km = over-water distance to first land (100 = open); open_ocean = no land within 100 km.\n")
    OUT.write_text(header + yaml.safe_dump({"spots": data}, sort_keys=True, default_flow_style=None, width=140),
                   encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    asyncio.run(main(sys.argv[1:]))
